// Fills in public/js/preset-data.js: each count's bet ramp and every premade strategy's
// simulated edge. The ramp raises the bet where the player's edge (flat betting, the
// strategy's own index plays) reaches +0.5%, +1%, +1.5% and +2%: 2, 4, 6 and 8 units.
//
// Usage: node scripts/build-presets.mjs [indexes.json from compute-indexes.mjs] [rounds=40000000]
import fs from 'fs';
import { simulate, edgeOf } from '../public/js/sim.js';
import { PRESETS } from '../public/js/strategies.js';
import { INDEXES as OLD_INDEXES } from '../public/js/preset-data.js';

const FILE = new URL('../public/js/preset-data.js', import.meta.url);
const INDEXES = process.argv[2] ? (({ ko, hiopt2, omega2 }) => ({ ko, hiopt2, omega2 }))(JSON.parse(fs.readFileSync(process.argv[2], 'utf8'))) : OLD_INDEXES;
const ROUNDS = Number(process.argv[3]) || 40_000_000;
const BATCH = 2_000_000;
const COUNT_OF = { i18: 'hilo', ko: 'ko', hiopt2: 'hiopt2', omega2: 'omega2' };

/** @param {import('../public/js/strategy.js').Strategy} s @param {number} rounds @param {Record<number, number[]>} [track] */
function run(s, rounds, track) {
  let sum = null; let state;
  for (let done = 0; done < rounds; done += BATCH) {
    const r = simulate(s, { rounds: Math.min(BATCH, rounds - done), state, track });
    state = r.state;
    sum = sum ? { ...sum, rounds: sum.rounds + r.rounds, flatWin: sum.flatWin + r.flatWin, flatSq: sum.flatSq + r.flatSq, rampWin: sum.rampWin + r.rampWin, rampSq: sum.rampSq + r.rampSq, rampBet: sum.rampBet + r.rampBet } : r;
  }
  return edgeOf(sum);
}

/** Least-squares line through the per-count edges (weighted by how often each count comes up). */
function rampFor(s) {
  /** @type {Record<number, number[]>} */
  const track = {};
  run({ ...s, ramp: [] }, ROUNDS / 2, track);
  const pts = Object.entries(track).map(([k, [n, w]]) => [Number(k), (100 * w) / n, n]).filter(([, , n]) => n >= 20000);
  let sw = 0; let sx = 0; let sy = 0; let sxx = 0; let sxy = 0;
  for (const [x, y, w] of pts) { sw += w; sx += w * x; sy += w * y; sxx += w * x * x; sxy += w * x * y; }
  const slope = (sw * sxy - sx * sy) / (sw * sxx - sx * sx);
  const icpt = (sy - slope * sx) / sw;
  const at = (edge) => Math.ceil((edge - icpt) / slope);
  console.error(`  ${s.id}: edge ≈ ${icpt.toFixed(2)}% + ${slope.toFixed(3)}% per point`);
  const ramp = [[0.5, 2], [1, 4], [1.5, 6], [2, 8]].map(([e, units]) => ({ at: at(e), units }));
  // Keep steps distinct (a steep count can hit two thresholds at one index).
  return ramp.filter((r, i) => i === ramp.length - 1 || r.at < ramp[i + 1].at);
}

const RAMPS = { hilo: null, ko: null, hiopt2: null, omega2: null };
for (const s of PRESETS) {
  const c = COUNT_OF[s.id];
  if (c) RAMPS[c] = rampFor(s);
}
const EDGES = {};
for (const s of PRESETS) {
  const ramp = COUNT_OF[s.id] ? RAMPS[COUNT_OF[s.id]] : s.ramp;
  const e = run({ ...s, ramp }, ROUNDS);
  EDGES[s.id] = { flat: Math.round(e.flat * 100) / 100, ramp: Math.round(e.ramp * 100) / 100, hands: e.hands };
  console.error(`  ${s.id}: flat ${e.flat.toFixed(2)}% ± ${e.flatSE.toFixed(2)}, ramp ${e.ramp.toFixed(2)}% ± ${e.rampSE.toFixed(2)}`);
}

const json = (o) => JSON.stringify(o).replace(/"(\w+)":/g, '$1: ').replace(/,/g, ', ').replace(/\{/g, '{ ').replace(/\}/g, ' }');
fs.writeFileSync(FILE, `// Generated by scripts/build-presets.mjs: do not edit by hand.
// INDEXES: computed by scripts/compute-indexes.mjs (400,000 shoe spots per count).
// RAMPS: where each count's player edge reaches +0.5/+1/+1.5/+2% (2/4/6/8 units).
// EDGES: simulated player edge, % of money bet (negative = house edge), ${(ROUNDS / 1e6).toFixed(0)} million rounds each.
export const INDEXES = ${JSON.stringify(INDEXES)};
export const RAMPS = ${json(RAMPS)};
/** @type {Record<string, { flat: number, ramp: number, hands: number } | undefined>} */
export const EDGES = ${json(EDGES)};
`);
console.error('wrote public/js/preset-data.js');
